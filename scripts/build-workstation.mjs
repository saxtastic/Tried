#!/usr/bin/env node
/* Bundle the workstation's declared data into a script the page can read.
 *
 * The page cannot fetch its own data: public/_headers ships
 * default-src 'none', which blocks connect-src along with everything else.
 * The simulator project hit this first and solved it the same way. Declared
 * inputs stay in workstation/*.json as the source of truth; this writes the
 * bundle, and check-workstation asserts the bundle has not drifted from them.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC = path.join(ROOT, "workstation");
const OUT = path.join(ROOT, "public", "workstation", "data.js");

const cards = JSON.parse(fs.readFileSync(path.join(SRC, "cards.json"), "utf8"));
const sets = fs.readdirSync(path.join(SRC, "questions")).filter((f) => f.endsWith(".json")).sort()
  .map((f) => JSON.parse(fs.readFileSync(path.join(SRC, "questions", f), "utf8")));

const payload = { cards, sets };
fs.writeFileSync(OUT, "/* Generated by scripts/build-workstation.mjs. Do not edit. */\nwindow.WORKSTATION = " + JSON.stringify(payload, null, 2) + ";\n");
console.log(`bundled ${cards.cards.length} cards and ${sets.length} question sets → ${path.relative(ROOT, OUT)}`);
